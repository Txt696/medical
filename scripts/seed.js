// deterministic pseudo-random so the demo looks the same every time
let seed = 42;
const rnd = () => { seed = (seed * 16807) % 2147483647; return (seed - 1) / 2147483646; };

transaction(() => {
  const ids = pharmacies.map((p) => {
    const id = db.prepare('INSERT INTO pharmacies (name, city, address, phone, hours) VALUES (?, ?, ?, ?, ?)')
      .run(p.name, p.city, p.address, p.phone, p.hours).lastInsertRowid;
    createUser({ login: p.login, password: 'demo123', role: 'pharmacy', pharmacyId: id });
    return id;
  });
  for (const [name, inn, form, dosage, pack, manufacturer, country, category, rx, base] of drugs) {
    const { drug } = findOrCreateDrug({ name, inn, form, dosage, pack, manufacturer, country, category, rx: rx ? '1' : '0' });
    ids.forEach((pid, i) => {
      if (rnd() < 0.2 && i > 0) return; // not every pharmacy has everything
      const factor = [1, 0.9, 0.82, 1.08][i] * (0.9 + rnd() * 0.25);
      const price = Math.round(base * factor * 10) / 10;
      const qty = rnd() < 0.1 ? 0 : Math.floor(rnd() * 40) + 1;
      upsertOffer(pid, drug.id, price, qty);
    });
  }
});

